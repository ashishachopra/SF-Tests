    WITH RECURSIVE cycle_paths AS (
        -- Base case: Start from filtered nodes only
        SELECT 
            fn.NODE_ID as start_node,
            fn.NODE_ID as current_node,
            fn.NODE_TYPE as start_node_type,
            ARRAY_CONSTRUCT(fn.NODE_ID) as path,
            1 as hop_count
        FROM FILTERED_NODES fn
        
        UNION ALL
        
        -- Recursive case: Expand paths
        SELECT 
            cp.start_node,
            neighbor.VALUE::VARCHAR as current_node,
            cp.start_node_type,
            ARRAY_APPEND(cp.path, neighbor.VALUE::VARCHAR) as path,
            cp.hop_count + 1
        FROM cycle_paths cp
        INNER JOIN FILTERED_NODES fn 
            ON cp.current_node = fn.NODE_ID
        CROSS JOIN LATERAL FLATTEN(input => fn.OUT_NEIGHBORS) neighbor
        WHERE cp.hop_count < :V_MAX_HOPS
          AND NOT ARRAY_CONTAINS(neighbor.VALUE::VARCHAR::VARIANT, cp.path)
          -- Early termination: Stop if we can reach start node
          AND (cp.hop_count < 2 OR neighbor.VALUE::VARCHAR != cp.start_node)
    )
    SELECT 
        start_node,
        current_node,
        start_node_type,
        path,
        hop_count
    FROM cycle_paths
    WHERE current_node = start_node
      AND hop_count >= 3
      AND hop_count <= :V_MAX_HOPS;
    
    -- Get count
    SELECT COUNT(*) INTO :V_ROWS_FOUND FROM CYCLE_PATHS_TEMP;
    
    -- Store results with enriched metadata
    CREATE OR REPLACE TABLE IDENTIFIER(:P_OUTPUT_TABLE) AS
    SELECT 
        cpt.start_node,
        cpt.start_node_type,
        cpt.path,
        cpt.cycle_length,
        CURRENT_TIMESTAMP() as detected_at,
        :P_MAX_HOPS as max_hops_searched,
        :P_NODE_TYPES as node_types_filter
    FROM (
        SELECT 
            start_node,
            start_node_type,
            path,
            hop_count as cycle_length
        FROM CYCLE_PATHS_TEMP
    ) cpt;
    
    RETURN ''V2: Found '' || V_ROWS_FOUND || '' cycles in '' || 
           DATEDIFF(SECOND, :V_START_TIME, CURRENT_TIMESTAMP()) || '' seconds. Filtered to node types: '' || :P_NODE_TYPES;
END;
';
CREATE OR REPLACE PROCEDURE ""SP_DEEP_TRAVERSAL""(""RESULT_TABLE_NAME"" VARCHAR DEFAULT 'DEEP_TRAVERSAL_RESULTS', ""MAX_HOPS"" NUMBER(38,0) DEFAULT 10, ""START_NODE_TYPE"" VARCHAR DEFAULT 'Customer')
RETURNS VARCHAR
LANGUAGE SQL
COMMENT='Performs deep graph traversal starting from nodes of a specified type, exploring up to MAX_HOPS levels and storing results in DEEP_TRAVERSAL_RESULTS table'
EXECUTE AS OWNER
AS '
DECLARE
    row_count INTEGER;
    current_hop INTEGER DEFAULT 0;
    result_msg VARCHAR;
BEGIN
    -- Create temp table for current frontier
    CREATE OR REPLACE TEMPORARY TABLE temp_current_frontier (
        node_id VARCHAR,
        node_type VARCHAR,
        node_name VARCHAR,
        hop_number INTEGER,
        path VARCHAR,
        path_nodes ARRAY,
        path_edges ARRAY
    );
    
    -- Create temp table for visited nodes to avoid cycles
    CREATE OR REPLACE TEMPORARY TABLE temp_visited_nodes (
        node_id VARCHAR PRIMARY KEY
    );
    
    -- Create temp table for all traversal results
    CREATE OR REPLACE TEMPORARY TABLE temp_all_results (
        node_id VARCHAR,
        node_type VARCHAR,
        node_name VARCHAR,
        node_props VARIANT,
        hop_number INTEGER,
        path VARCHAR,
        path_nodes ARRAY,
        path_edges ARRAY,
        edge_id VARCHAR,
        edge_type VARCHAR,
        edge_weight FLOAT,
        parent_node_id VARCHAR
    );
    
    -- Initialize with starting nodes of the specified type
    INSERT INTO temp_current_frontier
    SELECT 
        NODE_ID,
        NODE_TYPE,
        NAME,
        0 AS hop_number,
        NODE_ID AS path,
        ARRAY_CONSTRUCT(NODE_ID) AS path_nodes,
        ARRAY_CONSTRUCT() AS path_edges
    FROM A01A0E_GBU_FINCRIME_POC.GRAPH_ONTOLOGY.KG_NODE
    WHERE NODE_TYPE = :START_NODE_TYPE;
    
    -- Insert starting nodes into visited
    INSERT INTO temp_visited_nodes
    SELECT node_id FROM temp_current_frontier;
    
    -- Insert starting nodes into results
    INSERT INTO temp_all_results
    SELECT 
        n.NODE_ID,
        n.NODE_TYPE,
        n.NAME,
        n.PROPS,
        0 AS hop_number,
        n.NODE_ID AS path,
        ARRAY_CONSTRUCT(n.NODE_ID) AS path_nodes,
        ARRAY_CONSTRUCT() AS path_edges,
        NULL AS edge_id,
        NULL AS edge_type,
        NULL AS edge_weight,
        NULL AS parent_node_id
    FROM A01A0E_GBU_FINCRIME_POC.GRAPH_ONTOLOGY.KG_NODE n
    WHERE n.NODE_TYPE = :START_NODE_TYPE;
    
    -- Traverse up to MAX_HOPS
    WHILE (current_hop < :MAX_HOPS) DO
        current_hop := current_hop + 1;
        
        -- Find next frontier: neighbors of current frontier that haven''t been visited
        CREATE OR REPLACE TEMPORARY TABLE temp_next_frontier AS
        SELECT DISTINCT
            dst.NODE_ID,
            dst.NODE_TYPE,
            dst.NAME,
            :current_hop AS hop_number,
            cf.path || '' -> '' || dst.NODE_ID AS path,
            ARRAY_APPEND(cf.path_nodes, dst.NODE_ID) AS path_nodes,
            ARRAY_APPEND(cf.path_edges, e.EDGE_ID) AS path_edges,
            e.EDGE_ID,
            e.EDGE_TYPE,
            e.WEIGHT AS edge_weight,
            cf.node_id AS parent_node_id
        FROM temp_current_frontier cf
        JOIN A01A0E_GBU_FINCRIME_POC.GRAPH_ONTOLOGY.KG_EDGE e 
            ON cf.node_id = e.SRC_ID
        JOIN A01A0E_GBU_FINCRIME_POC.GRAPH_ONTOLOGY.KG_NODE dst 
            ON e.DST_ID = dst.NODE_ID
        LEFT JOIN temp_visited_nodes v 
            ON dst.NODE_ID = v.node_id
        WHERE v.node_id IS NULL;
        
        -- Check if we found any new nodes
        SELECT COUNT(*) INTO :row_count FROM temp_next_frontier;
        
        -- If no new nodes, exit loop
        IF (row_count = 0) THEN
            EXIT;
        END IF;
        
        -- FIXED: Changed nf.NODE_NAME to nf.NAME (the temp table has column NAME, not NODE_NAME)
        INSERT INTO temp_all_results
        SELECT 
            nf.NODE_ID,
            nf.NODE_TYPE,
            nf.NAME,
            n.PROPS,
            nf.hop_number,
            nf.path,
            nf.path_nodes,
            nf.path_edges,
            nf.EDGE_ID,
            nf.EDGE_TYPE,
            nf.edge_weight,
            nf.parent_node_id
        FROM temp_next_frontier nf
        JOIN A01A0E_GBU_FINCRIME_POC.GRAPH_ONTOLOGY.KG_NODE n 
            ON nf.NODE_ID = n.NODE_ID;
        
        -- Mark new nodes as visited
        INSERT INTO temp_visited_nodes
        SELECT DISTINCT node_id FROM temp_next_frontier;
        
        -- Move next frontier to current frontier
        DROP TABLE temp_current_frontier;
        ALTER TABLE temp_next_frontier RENAME TO temp_current_frontier;
    END WHILE;
    
    -- Write results to final output table
    CREATE OR REPLACE TABLE A01A0E_GBU_FINCRIME_POC.GRAPH_ONTOLOGY.DEEP_TRAVERSAL_RESULTS AS
    SELECT 
        node_id,
        node_type,
        node_name,
        node_props,
        hop_number,
        path,
        path_nodes,
        path_edges,
        edge_id,
        edge_type,
        edge_weight,
        parent_node_id,
        CURRENT_TIMESTAMP() AS traversal_timestamp
    FROM temp_all_results
    ORDER BY hop_number, node_id;
    
    -- Get final count
    SELECT COUNT(*) INTO :row_count FROM A01A0E_GBU_FINCRIME_POC.GRAPH_ONTOLOGY.DEEP_TRAVERSAL_RESULTS;
    
    result_msg := ''Deep traversal completed. Traversed '' || :row_count || '' nodes up to '' || :current_hop || '' hops starting from node type: '' || :START_NODE_TYPE;
    
    -- Cleanup temp tables
    DROP TABLE IF EXISTS temp_current_frontier;
    DROP TABLE IF EXISTS temp_visited_nodes;
    DROP TABLE IF EXISTS temp_all_results;
    
    RETURN result_msg;
END;
';
CREATE OR REPLACE PROCEDURE ""SP_DEEP_TRAVERSAL_OPTIMIZED""(""P_RESULT_TABLE_NAME"" VARCHAR DEFAULT 'DEEP_TRAVERSAL_RESULTS', ""P_MAX_HOPS"" NUMBER(38,0) DEFAULT 10, ""P_START_NODE_TYPE"" VARCHAR DEFAULT 'CUSTOMER', ""P_START_NODE_ID"" VARCHAR DEFAULT null)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS '
DECLARE
    v_row_count INTEGER;
    v_current_hop INTEGER DEFAULT 0;
    v_result_msg VARCHAR;
BEGIN
    -- Single temp table for frontier (simpler state management)
    CREATE OR REPLACE TEMPORARY TABLE temp_frontier (
        node_id VARCHAR,
        hop_number INTEGER,
        path_nodes ARRAY,
        path_edges ARRAY,
        PRIMARY KEY (node_id)  -- Implicit deduplication
    );
    
    -- Visited set
    CREATE OR REPLACE TEMPORARY TABLE temp_visited (
        node_id VARCHAR PRIMARY KEY
    );
    
    -- Results accumulator
    CREATE OR REPLACE TEMPORARY TABLE temp_results (
        node_id VARCHAR,
        node_type VARCHAR,
        node_name VARCHAR,
        node_props VARIANT,
        hop_number INTEGER,
        path_nodes ARRAY,
        path_edges ARRAY,
        edge_id VARCHAR,
        edge_type VARCHAR,
        edge_weight FLOAT,
        parent_node_id VARCHAR
    );
    
    -- Initialize with starting nodes (either specific ID or all of type)
    IF (P_START_NODE_ID IS NOT NULL) THEN
        INSERT INTO temp_frontier
        SELECT 
            NODE_ID,
            0 AS hop_number,
            ARRAY_CONSTRUCT(NODE_ID) AS path_nodes,
            ARRAY_CONSTRUCT() AS path_edges
        FROM A01A0E_GBU_FINCRIME_POC.GRAPH_ONTOLOGY.VW_GRAPH_NODES_ENRICHED_OPTIMIZED
        WHERE NODE_ID = :P_START_NODE_ID;
    ELSE
        INSERT INTO temp_frontier
        SELECT 
            NODE_ID,
            0 AS hop_number,
            ARRAY_CONSTRUCT(NODE_ID) AS path_nodes,
            ARRAY_CONSTRUCT() AS path_edges
        FROM A01A0E_GBU_FINCRIME_POC.GRAPH_ONTOLOGY.VW_GRAPH_NODES_ENRICHED_OPTIMIZED
        WHERE NODE_TYPE = :P_START_NODE_TYPE;
    END IF;
    
    -- Mark as visited
    INSERT INTO temp_visited SELECT node_id FROM temp_frontier;
    
    -- Insert starting nodes
    INSERT INTO temp_results
    SELECT 
        n.NODE_ID,
        n.NODE_TYPE,
        n.NAME,
        n.PROPS,
        0 AS hop_number,
        ARRAY_CONSTRUCT(n.NODE_ID) AS path_nodes,
        ARRAY_CONSTRUCT() AS path_edges,
        NULL AS edge_id,
        NULL AS edge_type,
        NULL AS edge_weight,
        NULL AS parent_node_id
    FROM A01A0E_GBU_FINCRIME_POC.GRAPH_ONTOLOGY.VW_GRAPH_NODES_ENRICHED_OPTIMIZED n
    WHERE n.NODE_ID IN (SELECT node_id FROM temp_frontier);
    
    -- Traversal loop using adjacency matrix
    WHILE (:v_current_hop < :P_MAX_HOPS) DO
        v_current_hop := :v_current_hop + 1;
        
        -- Expand frontier using pre-built adjacency (much faster than joining edges)
        CREATE OR REPLACE TEMPORARY TABLE temp_next_frontier AS
        SELECT DISTINCT
            neighbor.VALUE:neighbor_id::VARCHAR AS node_id,
            :v_current_hop AS hop_number,
            ARRAY_APPEND(f.path_nodes, neighbor.VALUE:neighbor_id::VARCHAR) AS path_nodes,
            ARRAY_APPEND(f.path_edges, neighbor.VALUE:edge_id::VARCHAR) AS path_edges,
            neighbor.VALUE:edge_id::VARCHAR AS edge_id,
            neighbor.VALUE:edge_type::VARCHAR AS edge_type,
            neighbor.VALUE:weight::FLOAT AS edge_weight,
            f.node_id AS parent_node_id
        FROM temp_frontier f
        INNER JOIN A01A0E_GBU_FINCRIME_POC.GRAPH_ONTOLOGY.GRAPH_ADJACENCY_FULL adj
            ON f.node_id = adj.node_id
        CROSS JOIN LATERAL FLATTEN(input => adj.out_neighbors) AS neighbor
        LEFT JOIN temp_visited v ON neighbor.VALUE:neighbor_id::VARCHAR = v.node_id
        WHERE v.node_id IS NULL;  -- Only unvisited nodes
        
        -- Check if expansion found new nodes
        SELECT COUNT(*) INTO :v_row_count FROM temp_next_frontier;
        IF (:v_row_count = 0) THEN
            EXIT;  -- No more nodes to explore
        END IF;
        
        -- Add to results with node enrichment
        INSERT INTO temp_results
        SELECT 
            nf.node_id,
            n.NODE_TYPE,
            n.NAME,
            n.PROPS,
            nf.hop_number,
            nf.path_nodes,
            nf.path_edges,
            nf.edge_id,
            nf.edge_type,
            nf.edge_weight,
            nf.parent_node_id
        FROM temp_next_frontier nf
        INNER JOIN A01A0E_GBU_FINCRIME_POC.GRAPH_ONTOLOGY.VW_GRAPH_NODES_ENRICHED_OPTIMIZED n
            ON nf.node_id = n.NODE_ID;
        
        -- Update visited
        INSERT INTO temp_visited 
        SELECT DISTINCT node_id FROM temp_next_frontier;
        
        -- Swap frontier tables
        DROP TABLE temp_frontier;
        ALTER TABLE temp_next_frontier RENAME TO temp_frontier;
    END WHILE;
    
    -- Write final results
    EXECUTE IMMEDIATE ''CREATE OR REPLACE TABLE A01A0E_GBU_FINCRIME_POC.GRAPH_ONTOLOGY.'' || :P_RESULT_TABLE_NAME || '' AS
    SELECT 
        node_id,
        node_type,
        node_name,
        node_props,
        hop_number,
        ARRAY_TO_STRING(path_nodes, '''' -> '''') AS path,
        path_nodes,
        path_edges,
        edge_id,
        edge_type,
        edge_weight,
        parent_node_id,
        CURRENT_TIMESTAMP() AS traversal_timestamp
    FROM temp_results
    ORDER BY hop_number, node_id'';
    
    SELECT COUNT(*) INTO :v_row_count FROM temp_results;
    
    v_result_msg := ''OPTIMIZED Deep traversal completed. Traversed '' || :v_row_count || 
                    '' nodes up to '' || :v_current_hop || '' hops'' ||
                    CASE WHEN :P_START_NODE_ID IS NOT NULL 
                         THEN '' from node: '' || :P_START_NODE_ID
                         ELSE '' from node type: '' || :P_START_NODE_TYPE 
                    END;
    
    -- Cleanup
    DROP TABLE IF EXISTS temp_frontier;
    DROP TABLE IF EXISTS temp_visited;
    DROP TABLE IF EXISTS temp_results;
    
    RETURN v_result_msg;
END;
';
CREATE OR REPLACE PROCEDURE ""SP_DEEP_TRAVERSAL_SQL""(""P_RESULT_TABLE_NAME"" VARCHAR DEFAULT 'DEEP_TRAVERSAL_RESULTS', ""P_MAX_HOPS"" NUMBER(38,0) DEFAULT 10, ""P_START_NODE_TYPE"" VARCHAR DEFAULT 'Customer')
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS '
DECLARE
    V_NODE_COUNT NUMBER;
    V_EDGE_COUNT NUMBER;
    V_START_NODE_COUNT NUMBER;
    V_RESULT_COUNT NUMBER;
    V_FULL_TABLE_NAME VARCHAR;
    V_START_TIME TIMESTAMP := CURRENT_TIMESTAMP();
    V_END_TIME TIMESTAMP;
    V_DURATION_SECONDS NUMBER;
BEGIN
    -- Set the full table name with schema prefix
    V_FULL_TABLE_NAME := ''A01A0E_GBU_FINCRIME_POC.GRAPH_ONTOLOGY.'' || :P_RESULT_TABLE_NAME;
    
    -- Get graph metrics
    SELECT COUNT(*) INTO :V_NODE_COUNT 
    FROM A01A0E_GBU_FINCRIME_POC.GRAPH_ONTOLOGY.KG_NODE;
    
    SELECT COUNT(*) INTO :V_EDGE_COUNT 
    FROM A01A0E_GBU_FINCRIME_POC.GRAPH_ONTOLOGY.KG_EDGE;
    
    SELECT COUNT(*) INTO :V_START_NODE_COUNT 
    FROM A01A0E_GBU_FINCRIME_POC.GRAPH_ONTOLOGY.KG_NODE 
    WHERE NODE_TYPE = :P_START_NODE_TYPE;
    
    -- Truncate result table before inserting new results
    EXECUTE IMMEDIATE ''TRUNCATE TABLE IF EXISTS '' || :V_FULL_TABLE_NAME;
    
    -- ============================================================================
    -- OPTIMIZED DEEP TRAVERSAL WITH BFS ALGORITHM
    -- ============================================================================
    -- Data structure insights:
    -- - KG_NODE: 150k nodes with NODE_ID, NODE_TYPE, NAME, PROPS
    -- - KG_EDGE: 156k edges with SRC_ID, DST_ID, EDGE_TYPE, WEIGHT
    -- - Result table: 20 columns including hop counts and node type distributions
    --
    -- Performance optimizations:
    -- 1. QUALIFY for efficient deduplication (better than DISTINCT)
    -- 2. Batch limiting with ROW_NUMBER for memory efficiency (100 nodes)
    -- 3. Single-pass conditional aggregation for all metrics
    -- 4. Pre-materialized node type lookup table
    -- 5. Direct dynamic SQL execution for flexibility
    -- ============================================================================
    
    EXECUTE IMMEDIATE ''
    INSERT INTO '' || :V_FULL_TABLE_NAME || ''
    WITH 
    -- Step 1: Select starting nodes efficiently (limit to 100 for performance)
    start_nodes AS (
        SELECT 
            NODE_ID,
            NODE_TYPE,
            NAME
        FROM A01A0E_GBU_FINCRIME_POC.GRAPH_ONTOLOGY.KG_NODE
        WHERE NODE_TYPE = '''''' || :P_START_NODE_TYPE || ''''''
        QUALIFY ROW_NUMBER() OVER (ORDER BY NODE_ID) <= 100
    ),
    
    -- Step 2: Pre-materialize node type map for faster joins
    node_type_map AS (
        SELECT 
            NODE_ID,
            NODE_TYPE
        FROM A01A0E_GBU_FINCRIME_POC.GRAPH_ONTOLOGY.KG_NODE
    ),
    
    -- Step 3: Recursive BFS traversal up to MAX_HOPS
    graph_traversal AS (
        -- Anchor: Starting nodes at hop 0
        SELECT 
            sn.NODE_ID AS start_node_id,
            sn.NODE_TYPE AS start_node_type,
            sn.NAME AS start_node_name,
            sn.NODE_ID AS current_node,
            0 AS hop_level
        FROM start_nodes sn
        
        UNION ALL
        
        -- Recursive: Traverse edges to next hop
        SELECT 
            gt.start_node_id,
            gt.start_node_type,
            gt.start_node_name,
            e.DST_ID AS current_node,
            gt.hop_level + 1 AS hop_level
        FROM graph_traversal gt
        INNER JOIN A01A0E_GBU_FINCRIME_POC.GRAPH_ONTOLOGY.KG_EDGE e 
            ON gt.current_node = e.SRC_ID
        WHERE gt.hop_level < '' || :P_MAX_HOPS || ''
    ),
    
    -- Step 4: Deduplicate efficiently - keep first occurrence of each (start, node) pair
    unique_traversal AS (
        SELECT 
            start_node_id,
            start_node_type,
            start_node_name,
            current_node,
            hop_level
        FROM graph_traversal
        QUALIFY ROW_NUMBER() OVER (
            PARTITION BY start_node_id, current_node 
            ORDER BY hop_level
        ) = 1
    ),
    
    -- Step 5: Join with node types for reachable nodes
    traversal_with_types AS (
        SELECT 
            ut.start_node_id,
            ut.start_node_type,
            ut.start_node_name,
            ut.current_node,
            ut.hop_level,
            COALESCE(ntm.NODE_TYPE, ''''Unknown'''') AS current_node_type
        FROM unique_traversal ut
        LEFT JOIN node_type_map ntm ON ut.current_node = ntm.NODE_ID
        WHERE ut.hop_level > 0  -- Exclude start node from reachable counts
    ),
    
    -- Step 6: Single-pass aggregation for all metrics
    aggregated_metrics AS (
        SELECT
            start_node_id,
            start_node_type,
            start_node_name,
            
            -- Total reachability metrics
            COUNT(DISTINCT current_node) AS total_reachable_nodes,
            MAX(hop_level) AS max_hop_reached,
            
            -- Nodes per hop using conditional aggregation
            COUNT(DISTINCT CASE WHEN hop_level = 1 THEN current_node END) AS nodes_at_hop_1,
            COUNT(DISTINCT CASE WHEN hop_level = 2 THEN current_node END) AS nodes_at_hop_2,
            COUNT(DISTINCT CASE WHEN hop_level = 3 THEN current_node END) AS nodes_at_hop_3,
            COUNT(DISTINCT CASE WHEN hop_level = 4 THEN current_node END) AS nodes_at_hop_4,
            COUNT(DISTINCT CASE WHEN hop_level = 5 THEN current_node END) AS nodes_at_hop_5,
            COUNT(DISTINCT CASE WHEN hop_level = 6 THEN current_node END) AS nodes_at_hop_6,
            COUNT(DISTINCT CASE WHEN hop_level = 7 THEN current_node END) AS nodes_at_hop_7,
            COUNT(DISTINCT CASE WHEN hop_level = 8 THEN current_node END) AS nodes_at_hop_8,
            COUNT(DISTINCT CASE WHEN hop_level = 9 THEN current_node END) AS nodes_at_hop_9,
            COUNT(DISTINCT CASE WHEN hop_level = 10 THEN current_node END) AS nodes_at_hop_10,
            
            -- Reachable nodes by type using conditional aggregation
            COUNT(DISTINCT CASE WHEN current_node_type = ''''Customer'''' THEN current_node END) AS reachable_customers,
            COUNT(DISTINCT CASE WHEN current_node_type = ''''Account'''' THEN current_node END) AS reachable_accounts,
            COUNT(DISTINCT CASE WHEN current_node_type = ''''Transaction'''' THEN current_node END) AS reachable_transactions,
            COUNT(DISTINCT CASE WHEN current_node_type = ''''Device'''' THEN current_node END) AS reachable_devices
        FROM traversal_with_types
        GROUP BY start_node_id, start_node_type, start_node_name
    ),
    
    -- Step 7: Build hop distribution JSON (node type breakdown per hop)
    hop_type_distribution AS (
        SELECT
            start_node_id,
            hop_level,
            OBJECT_AGG(
                current_node_type, 
                COUNT(DISTINCT current_node)
            ) AS type_dist
        FROM traversal_with_types
        GROUP BY start_node_id, hop_level
    ),
    
    hop_distribution_json AS (
        SELECT
            start_node_id,
            OBJECT_AGG(
                hop_level::VARCHAR,
                type_dist
            ) AS hop_distribution
        FROM hop_type_distribution
        GROUP BY start_node_id
    )
    
    -- Step 8: Final assembly - combine all metrics
    SELECT
        am.start_node_id AS START_NODE_ID,
        am.start_node_type AS START_NODE_TYPE,
        am.start_node_name AS START_NODE_NAME,
        am.total_reachable_nodes AS TOTAL_REACHABLE_NODES,
        am.max_hop_reached AS MAX_HOP_REACHED,
        am.nodes_at_hop_1 AS NODES_AT_HOP_1,
        am.nodes_at_hop_2 AS NODES_AT_HOP_2,
        am.nodes_at_hop_3 AS NODES_AT_HOP_3,
        am.nodes_at_hop_4 AS NODES_AT_HOP_4,
        am.nodes_at_hop_5 AS NODES_AT_HOP_5,
        am.nodes_at_hop_6 AS NODES_AT_HOP_6,
        am.nodes_at_hop_7 AS NODES_AT_HOP_7,
        am.nodes_at_hop_8 AS NODES_AT_HOP_8,
        am.nodes_at_hop_9 AS NODES_AT_HOP_9,
        am.nodes_at_hop_10 AS NODES_AT_HOP_10,
        TO_VARCHAR(COALESCE(hdj.hop_distribution, OBJECT_CONSTRUCT())) AS HOP_DISTRIBUTION,
        am.reachable_customers AS REACHABLE_CUSTOMERS,
        am.reachable_accounts AS REACHABLE_ACCOUNTS,
        am.reachable_transactions AS REACHABLE_TRANSACTIONS,
        am.reachable_devices AS REACHABLE_DEVICES
    FROM aggregated_metrics am
    LEFT JOIN hop_distribution_json hdj ON am.start_node_id = hdj.start_node_id'';
    
    -- Calculate execution time
    V_END_TIME := CURRENT_TIMESTAMP();
    V_DURATION_SECONDS := DATEDIFF(SECOND, :V_START_TIME, :V_END_TIME);
    
    -- Get result count using LET statement
    LET result_query := ''SELECT COUNT(*) FROM '' || :V_FULL_TABLE_NAME;
    LET result_cursor RESULTSET := (EXECUTE IMMEDIATE :result_query);
    LET result_cursor_row CURSOR FOR result_cursor;
    OPEN result_cursor_row;
    FETCH result_cursor_row INTO V_RESULT_COUNT;
    CLOSE result_cursor_row;
    
    -- Return success message with detailed statistics
    RETURN OBJECT_CONSTRUCT(
        ''status'', ''SUCCESS'',
        ''execution_time_seconds'', :V_DURATION_SECONDS,
        ''total_graph_nodes'', :V_NODE_COUNT,
        ''total_graph_edges'', :V_EDGE_COUNT,
        ''start_node_type'', :P_START_NODE_TYPE,
        ''nodes_analyzed'', LEAST(:V_START_NODE_COUNT, 100),
        ''max_hops_configured'', :P_MAX_HOPS,
        ''result_table'', :V_FULL_TABLE_NAME,
        ''result_count'', :V_RESULT_COUNT,
        ''avg_reachable_per_node'', ROUND(:V_RESULT_COUNT::FLOAT / NULLIF(LEAST(:V_START_NODE_COUNT, 100), 0), 2),
        ''optimization_level'', ''QUALIFY deduplication + single-pass conditional aggregation'',
        ''message'', ''Deep traversal completed in '' || :V_DURATION_SECONDS::VARCHAR || '' seconds. '' ||
                   ''Analyzed '' || LEAST(:V_START_NODE_COUNT, 100)::VARCHAR || '' '' || :P_START_NODE_TYPE || 
                   '' nodes up to '' || :P_MAX_HOPS::VARCHAR || '' hops. '' ||
                   ''Results written to '' || :V_FULL_TABLE_NAME || ''.''
    )::VARCHAR;
    
EXCEPTION
