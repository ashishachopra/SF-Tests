def analyze_cluster_characteristics_optimized(graph, subgraph, cluster_nodes):
    """"""Analyze characteristics with pre-computed subgraph."""""
    if len(cluster_nodes) < 2:
        return None
    
    # Use subgraph data directly (already computed)
    num_nodes = len(cluster_nodes)
    num_edges = subgraph.number_of_edges()
    
    # OPTIMIZATION: Vectorized node type extraction
    node_types = Counter([graph.nodes[n].get(''node_type'') for n in cluster_nodes])
    
    # OPTIMIZATION: Use subgraph edges (already filtered)
    edge_types = Counter([d.get(''edge_type'') for _, _, d in subgraph.edges(data=True)])
    
    # Density calculation
    possible_edges = num_nodes * (num_nodes - 1)
    density = num_edges / possible_edges if possible_edges > 0 else 0
    
    # OPTIMIZATION: Count external edges more efficiently
    internal_edges = num_edges
    external_edges = sum(
        1 for node in cluster_nodes 
        for neighbor in set(graph.neighbors(node)) | set(graph.predecessors(node))
        if neighbor not in cluster_nodes
    )
    
    # Average degree from subgraph
    avg_degree = sum(dict(subgraph.degree()).values()) / num_nodes if num_nodes > 0 else 0
    
    return {
        ''size'': num_nodes,
        ''num_edges'': num_edges,
        ''density'': density,
        ''avg_degree'': avg_degree,
        ''internal_edges'': internal_edges,
        ''external_edges'': external_edges,
        ''isolation_ratio'': internal_edges / (internal_edges + external_edges) if (internal_edges + external_edges) > 0 else 0,
        ''node_types'': node_types,
        ''edge_types'': edge_types
    }


def detect_fraud_ring_patterns_optimized(graph, subgraph, cluster_nodes, cluster_stats, skip_cycle_detection):
    """"""Optimized fraud pattern detection."""""
    if not cluster_stats:
        return {''flags'': [], ''risk_score'': 0}
    
    flags = []
    risk_score = 0
    
    # Pattern 1: High density cluster
    if cluster_stats[''density''] > 0.3 and cluster_stats[''size''] >= 5:
        flags.append(f""High density ({cluster_stats[''density'']:.2f}) with {cluster_stats[''size'']} members"")
        risk_score += 50
    
    # Pattern 2: Isolated cluster
    if cluster_stats[''isolation_ratio''] > 0.8 and cluster_stats[''size''] >= 4:
        flags.append(f""Highly isolated cluster ({cluster_stats[''isolation_ratio'']:.2f})"")
        risk_score += 40
    
    # Pattern 3: Device sharing
    if cluster_stats[''node_types''].get(''Device'', 0) >= 1 and cluster_stats[''node_types''].get(''Customer'', 0) >= 3:
        flags.append(f""{cluster_stats[''node_types''][''Customer'']} customers sharing devices"")
        risk_score += 45
    
    # OPTIMIZATION: Skip expensive cycle detection for large clusters or if disabled
    if not skip_cycle_detection and cluster_stats[''size''] < 50:
        try:
            # Limit cycle search depth to improve performance
            cycles = []
            for node in list(cluster_nodes)[:20]:  # Only check first 20 nodes
                try:
                    node_cycles = list(nx.simple_cycles(subgraph, node, length_bound=10))
                    cycles.extend(node_cycles[:5])  # Limit cycles per node
                    if len(cycles) >= 10:  # Stop if we found enough
                        break
                except:
                    pass
            
            if len(cycles) >= 2:
                flags.append(f""{len(cycles)} circular patterns detected"")
                risk_score += 55
        except:
            pass  # Skip if it takes too long
    
    # Pattern 5: Cross-ownership (optimized with list comprehensions)
    customers = cluster_stats[''node_types''].get(''Customer'', 0)
    accounts = cluster_stats[''node_types''].get(''Account'', 0)
    
    if customers >= 2 and accounts >= 5:
        ownership_edges = cluster_stats[''edge_types''].get(''OWNS'', 0)
        if ownership_edges >= 4:
            flags.append(f""{customers} customers own {accounts} accounts with cross-ownership"")
            risk_score += 60
    
    # Pattern 6: Rapid fund movement
    transfer_count = cluster_stats[''edge_types''].get(''TRANSFERRED_TO'', 0)
    if transfer_count >= 5 and cluster_stats[''size''] <= 10:
        flags.append(f""{transfer_count} internal transfers"")
        risk_score += 40
    
    # Pattern 7: Referral ring
    referral_count = cluster_stats[''edge_types''].get(''REFERRED'', 0)
    if referral_count >= 3 and customers >= 3:
        flags.append(f""{referral_count} mutual referrals"")
        risk_score += 45
    
    return {
        ''flags'': flags,
        ''risk_score'': risk_score
    }


def find_key_members_optimized(subgraph, cluster_nodes):
    """"""Optimized key member identification using pre-computed subgraph."""""
    if len(cluster_nodes) < 2:
        return []
    
    # OPTIMIZATION: Use simpler degree centrality only for large clusters
    if len(cluster_nodes) > 100:
        degree_centrality = nx.degree_centrality(subgraph)
        betweenness_centrality = {n: 0 for n in cluster_nodes}
    else:
        degree_centrality = nx.degree_centrality(subgraph)
        try:
            betweenness_centrality = nx.betweenness_centrality(subgraph)
        except:
            betweenness_centrality = {n: 0 for n in cluster_nodes}
    
    # OPTIMIZATION: Pre-filter nodes by centrality before creating full list
    key_members = []
    for node in cluster_nodes:
        total_centrality = degree_centrality.get(node, 0) + betweenness_centrality.get(node, 0)
        if total_centrality > 0.1:  # Only keep significant nodes
            node_data = subgraph.nodes[node]
            key_members.append({
                ''node_id'': node,
                ''node_type'': node_data.get(''node_type''),
                ''node_name'': node_data.get(''name''),
                ''degree_centrality'': degree_centrality.get(node, 0),
                ''betweenness_centrality'': betweenness_centrality.get(node, 0),
                ''total_centrality'': total_centrality
            })
    
    return sorted(key_members, key=lambda x: x[''total_centrality''], reverse=True)[:10]

