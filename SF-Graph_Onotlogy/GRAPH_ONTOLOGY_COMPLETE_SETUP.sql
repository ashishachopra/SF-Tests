CREATE OR REPLACE PROCEDURE ""GENERATE_ALL_TRANSACTION_EDGES_AUTOMATED""(""P_BATCH_SIZE"" NUMBER(38,0), ""P_MAX_BATCHES"" NUMBER(38,0))
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS '
BEGIN
    LET batch_num INT := 0;
    LET current_offset INT := 0;
    
    -- Generate FROM_ACCOUNT edges
    WHILE (:batch_num < :P_MAX_BATCHES) DO
        current_offset := :batch_num * :P_BATCH_SIZE;
        CALL A01A0E_GBU_FINCRIME_POC.GRAPH_ONTOLOGY.GENERATE_FROM_ACCOUNT_EDGES_CHUNK(:P_BATCH_SIZE, :current_offset);
        batch_num := :batch_num + 1;
    END WHILE;
    
    -- Reset for TO_ACCOUNT edges
    batch_num := 0;
    WHILE (:batch_num < :P_MAX_BATCHES) DO
        current_offset := :batch_num * :P_BATCH_SIZE;
        CALL A01A0E_GBU_FINCRIME_POC.GRAPH_ONTOLOGY.GENERATE_TO_ACCOUNT_EDGES_CHUNK(:P_BATCH_SIZE, :current_offset);
        batch_num := :batch_num + 1;
    END WHILE;
    
    -- Reset for INITIATED_FROM edges
    batch_num := 0;
    WHILE (:batch_num < :P_MAX_BATCHES) DO
        current_offset := :batch_num * :P_BATCH_SIZE;
        CALL A01A0E_GBU_FINCRIME_POC.GRAPH_ONTOLOGY.GENERATE_INITIATED_FROM_EDGES_CHUNK(:P_BATCH_SIZE, :current_offset);
        batch_num := :batch_num + 1;
