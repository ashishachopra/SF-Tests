CREATE OR REPLACE PROCEDURE ""GENERATE_FROM_ACCOUNT_EDGES_CHUNK""(""P_BATCH_SIZE"" NUMBER(38,0), ""P_OFFSET"" NUMBER(38,0))
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS '
BEGIN
    LET max_edge_num INT;
    LET rows_inserted INT;
    
    SELECT COALESCE(MAX(TRY_CAST(REPLACE(EDGE_ID, ''EDGE'', '''') AS INT)), 0)
    INTO :max_edge_num
    FROM A01A0E_GBU_FINCRIME_POC.GRAPH_ONTOLOGY.KG_EDGE
    WHERE EDGE_ID LIKE ''EDGE%'';
    
    INSERT INTO A01A0E_GBU_FINCRIME_POC.GRAPH_ONTOLOGY.KG_EDGE 
    (EDGE_ID, SRC_ID, DST_ID, EDGE_TYPE, WEIGHT, EFFECTIVE_START)
    WITH transactions AS (
        SELECT 
            NODE_ID,
            (ABS(HASH(NODE_ID)) % :P_BATCH_SIZE) + 1 AS target_account_position,
            ROW_NUMBER() OVER (ORDER BY NODE_ID) AS tx_row_num
        FROM A01A0E_GBU_FINCRIME_POC.GRAPH_ONTOLOGY.KG_NODE
        WHERE NODE_TYPE = ''Transaction''
        ORDER BY NODE_ID
        LIMIT :P_BATCH_SIZE OFFSET :P_OFFSET
    ),
    accounts AS (
        SELECT 
            NODE_ID,
            ROW_NUMBER() OVER (ORDER BY RANDOM()) AS account_position
        FROM A01A0E_GBU_FINCRIME_POC.GRAPH_ONTOLOGY.KG_NODE
        WHERE NODE_TYPE = ''Account''
        LIMIT :P_BATCH_SIZE
    )
    SELECT 
        ''EDGE'' || LPAD((:max_edge_num + t.tx_row_num), 8, ''0'') AS EDGE_ID,
        t.NODE_ID AS SRC_ID,
        a.NODE_ID AS DST_ID,
        ''FROM_ACCOUNT'' AS EDGE_TYPE,
        1.0 AS WEIGHT,
        CURRENT_DATE() AS EFFECTIVE_START
    FROM transactions t
    INNER JOIN accounts a ON t.target_account_position = a.account_position;
    
    rows_inserted := SQLROWCOUNT;
    
    RETURN ''Generated '' || :rows_inserted || '' FROM_ACCOUNT edges (batch size: '' || :P_BATCH_SIZE || '', offset: '' || :P_OFFSET || '')'';
END;
';
