    V_CYCLES_FOUND NUMBER;
    V_STATUS VARCHAR;
BEGIN
    V_EXECUTION_START := CURRENT_TIMESTAMP();
    
    -- Add HAS_CYCLE column if it doesn''t exist
    ALTER TABLE IDENTIFIER(:P_SOURCE_TABLE_NAME) ADD COLUMN IF NOT EXISTS HAS_CYCLE BOOLEAN DEFAULT FALSE;
    
    -- Create filtered graph edges for only nodes in significant clusters
    CREATE OR REPLACE TEMPORARY TABLE TEMP_CYCLE_CHECK_EDGES AS
    SELECT DISTINCT
        E.SRC_ID AS NODE_FROM,
        E.DST_ID AS NODE_TO
    FROM A01A0E_GBU_FINCRIME_POC.GRAPH_ONTOLOGY.KG_EDGE E
    INNER JOIN IDENTIFIER(:P_SOURCE_TABLE_NAME) C1 ON E.SRC_ID = C1.NODE_ID
    INNER JOIN IDENTIFIER(:P_SOURCE_TABLE_NAME) C2 ON E.DST_ID = C2.NODE_ID
    WHERE C1.CLUSTER_SIZE >= :P_MIN_CLUSTER_SIZE_FOR_CYCLE_CHECK
      AND C2.CLUSTER_SIZE >= :P_MIN_CLUSTER_SIZE_FOR_CYCLE_CHECK
      AND C1.CLUSTER_ID = C2.CLUSTER_ID;  -- Only check within same cluster
    
    -- Detect cycles with limited depth
    CREATE OR REPLACE TEMPORARY TABLE TEMP_CYCLE_NODES AS
    WITH RECURSIVE PATH_TRACE AS (
        SELECT 
            E.NODE_FROM AS START_NODE,
            E.NODE_TO AS CURRENT_NODE,
            1 AS PATH_LENGTH,
            E.NODE_FROM AS PATH,
            FALSE AS HAS_CYCLE
        FROM TEMP_CYCLE_CHECK_EDGES E
        
        UNION ALL
        
        SELECT 
            PT.START_NODE,
            E.NODE_TO AS CURRENT_NODE,
            PT.PATH_LENGTH + 1 AS PATH_LENGTH,
            PT.PATH,
            CASE 
                WHEN E.NODE_TO = PT.START_NODE THEN TRUE 
                ELSE PT.HAS_CYCLE 
            END AS HAS_CYCLE
        FROM PATH_TRACE PT
        INNER JOIN TEMP_CYCLE_CHECK_EDGES E ON PT.CURRENT_NODE = E.NODE_FROM
        WHERE PT.PATH_LENGTH < :P_MAX_PATH_DEPTH
          AND NOT PT.HAS_CYCLE
          AND PT.PATH != E.NODE_TO  -- Prevent immediate revisit
    )
    SELECT DISTINCT START_NODE AS NODE_ID
    FROM PATH_TRACE
    WHERE HAS_CYCLE = TRUE;
    
    -- Update source table with cycle information
    UPDATE IDENTIFIER(:P_SOURCE_TABLE_NAME) C
    SET HAS_CYCLE = TRUE
    WHERE EXISTS (
        SELECT 1 FROM TEMP_CYCLE_NODES CN WHERE CN.NODE_ID = C.NODE_ID
    );
    
    SELECT COUNT(*) INTO V_CYCLES_FOUND FROM TEMP_CYCLE_NODES;
    
    SELECT COUNT(DISTINCT NODE_ID) INTO V_NODES_CHECKED 
    FROM IDENTIFIER(:P_SOURCE_TABLE_NAME)
    WHERE CLUSTER_SIZE >= :P_MIN_CLUSTER_SIZE_FOR_CYCLE_CHECK;
    
    V_EXECUTION_END := CURRENT_TIMESTAMP();
    
    V_STATUS := ''SUCCESS: Checked '' || V_NODES_CHECKED || '' nodes in large clusters. '' ||
                ''Found '' || V_CYCLES_FOUND || '' nodes involved in cycles. '' ||
                ''Execution time: '' || DATEDIFF(''second'', V_EXECUTION_START, V_EXECUTION_END) || ''s.'';
    
    RETURN V_STATUS;
    
EXCEPTION
    WHEN OTHER THEN
        RETURN ''ERROR: '' || SQLERRM || '' (SQLCODE: '' || SQLCODE || '')'';
END;
