CREATE OR REPLACE PROCEDURE ""SP_CLUSTER_DETECTION_OPTIMIZED""(""P_RESULT_TABLE_NAME"" VARCHAR DEFAULT 'CLUSTER_ANALYSIS_RESULTS', ""P_MAX_NODES_TO_PROCESS"" NUMBER(38,0) DEFAULT 100000, ""P_SKIP_CYCLE_DETECTION"" BOOLEAN DEFAULT FALSE, ""P_MIN_CLUSTER_SIZE"" NUMBER(38,0) DEFAULT 3)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS CALLER
AS '
DECLARE
    V_ITERATION_COUNT NUMBER DEFAULT 0;
    V_MAX_ITERATIONS NUMBER DEFAULT 100;
    V_CHANGES_MADE NUMBER DEFAULT 1;
    V_TOTAL_NODES NUMBER;
    V_TOTAL_CLUSTERS NUMBER;
    V_EXECUTION_START TIMESTAMP_NTZ;
    V_EXECUTION_END TIMESTAMP_NTZ;
    V_STATUS VARCHAR;
    V_HAS_CYCLES BOOLEAN DEFAULT FALSE;
BEGIN
    V_EXECUTION_START := CURRENT_TIMESTAMP();
    
    -- Create result table if it doesn''t exist
    CREATE TABLE IF NOT EXISTS IDENTIFIER(:P_RESULT_TABLE_NAME) (
        CLUSTER_ID VARCHAR,
        NODE_ID VARCHAR,
        NODE_TYPE VARCHAR,
        NODE_NAME VARCHAR,
        CLUSTER_SIZE NUMBER,
        DEGREE NUMBER,
        HAS_CYCLE BOOLEAN,
        EXECUTION_TIMESTAMP TIMESTAMP_NTZ,
        PRIMARY KEY (NODE_ID)
    );
    
    -- Clear previous results
    DELETE FROM IDENTIFIER(:P_RESULT_TABLE_NAME);
    
    -- Create temporary table for graph edges (bidirectional)
    CREATE OR REPLACE TEMPORARY TABLE TEMP_GRAPH_EDGES AS
    SELECT SRC_ID AS NODE_FROM, DST_ID AS NODE_TO, WEIGHT
    FROM A01A0E_GBU_FINCRIME_POC.GRAPH_ONTOLOGY.KG_EDGE
    UNION ALL
    SELECT DST_ID AS NODE_FROM, SRC_ID AS NODE_TO, WEIGHT
    FROM A01A0E_GBU_FINCRIME_POC.GRAPH_ONTOLOGY.KG_EDGE;
    
    -- Initialize cluster assignments: each node starts in its own cluster
    CREATE OR REPLACE TEMPORARY TABLE TEMP_NODE_CLUSTERS AS
    SELECT 
        N.NODE_ID,
        N.NODE_TYPE,
        N.NAME,
        N.NODE_ID AS CLUSTER_ID,
        0 AS DEGREE
    FROM A01A0E_GBU_FINCRIME_POC.GRAPH_ONTOLOGY.KG_NODE N
    LIMIT :P_MAX_NODES_TO_PROCESS;
    
    -- Calculate node degrees for optimization
    UPDATE TEMP_NODE_CLUSTERS NC
    SET DEGREE = (
        SELECT COUNT(*)
        FROM TEMP_GRAPH_EDGES E
        WHERE E.NODE_FROM = NC.NODE_ID
    );
    
    -- Iterative label propagation for cluster detection
    WHILE (V_CHANGES_MADE > 0 AND V_ITERATION_COUNT < V_MAX_ITERATIONS) DO
        V_ITERATION_COUNT := V_ITERATION_COUNT + 1;
        
        -- Update cluster assignments: each node adopts the minimum cluster_id from its neighbors
        CREATE OR REPLACE TEMPORARY TABLE TEMP_NEW_CLUSTERS AS
        SELECT 
            NC.NODE_ID,
            NC.NODE_TYPE,
            NC.NAME,
            NC.DEGREE,
            LEAST(
                NC.CLUSTER_ID,
                COALESCE(MIN(NC2.CLUSTER_ID), NC.CLUSTER_ID)
            ) AS NEW_CLUSTER_ID
        FROM TEMP_NODE_CLUSTERS NC
        LEFT JOIN TEMP_GRAPH_EDGES E ON NC.NODE_ID = E.NODE_FROM
        LEFT JOIN TEMP_NODE_CLUSTERS NC2 ON E.NODE_TO = NC2.NODE_ID
        GROUP BY NC.NODE_ID, NC.NODE_TYPE, NC.NAME, NC.CLUSTER_ID, NC.DEGREE;
        
        -- Count changes
        SELECT COUNT(*)
        INTO V_CHANGES_MADE
        FROM TEMP_NEW_CLUSTERS TNC
        JOIN TEMP_NODE_CLUSTERS NC ON TNC.NODE_ID = NC.NODE_ID
        WHERE TNC.NEW_CLUSTER_ID != NC.CLUSTER_ID;
        
        -- Apply changes
        CREATE OR REPLACE TEMPORARY TABLE TEMP_NODE_CLUSTERS AS
        SELECT 
            NODE_ID,
            NODE_TYPE,
            NAME,
            NEW_CLUSTER_ID AS CLUSTER_ID,
            DEGREE
        FROM TEMP_NEW_CLUSTERS;
    END WHILE;
    
    -- Calculate cluster sizes
    CREATE OR REPLACE TEMPORARY TABLE TEMP_CLUSTER_SIZES AS
    SELECT 
        CLUSTER_ID,
        COUNT(*) AS CLUSTER_SIZE
    FROM TEMP_NODE_CLUSTERS
    GROUP BY CLUSTER_ID;
    
    -- Detect cycles if requested
    IF (NOT :P_SKIP_CYCLE_DETECTION) THEN
        CREATE OR REPLACE TEMPORARY TABLE TEMP_CYCLE_DETECTION AS
        WITH RECURSIVE PATH_TRACE AS (
            -- Start: each edge is a potential path start
            SELECT 
                E.NODE_FROM AS START_NODE,
                E.NODE_FROM AS CURRENT_NODE,
                E.NODE_TO AS NEXT_NODE,
                1 AS PATH_LENGTH,
                E.NODE_FROM || ''->'' || E.NODE_TO AS PATH,
                FALSE AS HAS_CYCLE
            FROM TEMP_GRAPH_EDGES E
            
            UNION ALL
            
            -- Recursion: extend paths
            SELECT 
                PT.START_NODE,
                PT.NEXT_NODE AS CURRENT_NODE,
                E.NODE_TO AS NEXT_NODE,
                PT.PATH_LENGTH + 1 AS PATH_LENGTH,
                PT.PATH || ''->'' || E.NODE_TO AS PATH,
                CASE 
                    WHEN E.NODE_TO = PT.START_NODE THEN TRUE 
                    ELSE PT.HAS_CYCLE 
                END AS HAS_CYCLE
            FROM PATH_TRACE PT
            JOIN TEMP_GRAPH_EDGES E ON PT.NEXT_NODE = E.NODE_FROM
            WHERE PT.PATH_LENGTH < 10 
              AND NOT PT.HAS_CYCLE
              AND PT.PATH NOT LIKE ''%'' || E.NODE_TO || ''%''
        )
        SELECT DISTINCT START_NODE AS NODE_ID
        FROM PATH_TRACE
        WHERE HAS_CYCLE = TRUE;
        
        SELECT COUNT(*) > 0 INTO V_HAS_CYCLES FROM TEMP_CYCLE_DETECTION;
    END IF;
    
    -- Insert final results (filter by minimum cluster size)
    INSERT INTO IDENTIFIER(:P_RESULT_TABLE_NAME)
    SELECT 
        NC.CLUSTER_ID,
        NC.NODE_ID,
        NC.NODE_TYPE,
        NC.NAME AS NODE_NAME,
        CS.CLUSTER_SIZE,
        NC.DEGREE,
        CASE 
            WHEN :P_SKIP_CYCLE_DETECTION THEN NULL
            WHEN CD.NODE_ID IS NOT NULL THEN TRUE
            ELSE FALSE
        END AS HAS_CYCLE,
        CURRENT_TIMESTAMP() AS EXECUTION_TIMESTAMP
    FROM TEMP_NODE_CLUSTERS NC
    JOIN TEMP_CLUSTER_SIZES CS ON NC.CLUSTER_ID = CS.CLUSTER_ID
    LEFT JOIN (SELECT NODE_ID FROM TEMP_CYCLE_DETECTION) CD ON NC.NODE_ID = CD.NODE_ID
    WHERE CS.CLUSTER_SIZE >= :P_MIN_CLUSTER_SIZE
    ORDER BY CS.CLUSTER_SIZE DESC, NC.CLUSTER_ID, NC.NODE_ID;
    
    -- Get summary statistics
    SELECT COUNT(DISTINCT CLUSTER_ID) INTO V_TOTAL_CLUSTERS 
