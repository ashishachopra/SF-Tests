def detect_cycles_from_node(graph, start_node, max_depth):
    """""
    Detect all cycles starting from a given node up to max_depth hops.
    """""
    cycles = []
    visited_in_path = set()
    
    def dfs(current, path, depth):
        if depth > max_depth:
            return
        
        # Check if we''ve returned to the start node (cycle found)
        if len(path) > 1 and current == start_node:
            cycles.append(path[:])
            return
        
        # Avoid revisiting nodes in the current path
        if current in visited_in_path:
            return
        
        visited_in_path.add(current)
        
        # Explore neighbors
        for neighbor in graph.successors(current):
            dfs(neighbor, path + [neighbor], depth + 1)
        
        visited_in_path.remove(current)
    
    # Start DFS
    dfs(start_node, [start_node], 0)
    
    return cycles


def analyze_cycle(graph, cycle):
    """""
    Analyze a cycle and return detailed information.
    """""
    cycle_info = {
        ''length'': len(cycle) - 1,
        ''nodes'': cycle,
        ''node_types'': [],
        ''edge_types'': [],
        ''path_details'': []
    }
    
    for i in range(len(cycle) - 1):
        src = cycle[i]
        dst = cycle[i + 1]
        
        src_data = graph.nodes[src]
        dst_data = graph.nodes[dst]
        edge_data = graph.get_edge_data(src, dst)
        
        cycle_info[''node_types''].append(src_data.get(''node_type''))
        cycle_info[''edge_types''].append(edge_data.get(''edge_type'') if edge_data else ''Unknown'')
        
        cycle_info[''path_details''].append({
            ''from_id'': src,
            ''from_name'': src_data.get(''name''),
            ''from_type'': src_data.get(''node_type''),
            ''to_id'': dst,
            ''to_name'': dst_data.get(''name''),
            ''to_type'': dst_data.get(''node_type''),
            ''relationship'': edge_data.get(''edge_type'') if edge_data else ''Unknown''
        })
    
    # Create signature for deduplication
    cycle_info[''signature''] = tuple(sorted(cycle[:-1]))
    
    return cycle_info


def get_cycle_type(cycle_info):
    """""
    Classify the type of cycle based on node types.
    """""
    node_types = set(cycle_info[''node_types''])
    
    if node_types == {''Customer'', ''Account''}:
        return ''Customer-Account Cycle''
    elif node_types == {''Customer'', ''Device''}:
        return ''Customer-Device Cycle''
    elif ''Transaction'' in node_types and ''Account'' in node_types:
        return ''Transaction-Account Cycle''
    elif ''Customer'' in node_types and ''Transaction'' in node_types:
        return ''Customer-Transaction Cycle''
    elif len(node_types) >= 3:
        return ''Multi-Entity Cycle''
    else:
        return ''Other Cycle''


def is_suspicious_cycle(cycle_info):
    """""
    Check if a cycle exhibits suspicious patterns.
    """""
    suspicious = False
    reasons = []
    
    # Check for rapid round-trip patterns (money laundering)
    if ''Account'' in cycle_info[''node_types''] and cycle_info[''length''] <= 4:
        if ''TRANSFERRED_TO'' in cycle_info[''edge_types'']:
            transfer_count = cycle_info[''edge_types''].count(''TRANSFERRED_TO'')
            if transfer_count >= 2:
                suspicious = True
                reasons.append(f""Rapid account round-trip detected ({transfer_count} transfers in {cycle_info[''length'']} hops)"")
    
    # Check for device sharing in short cycles
    if ''Device'' in cycle_info[''node_types''] and ''Customer'' in cycle_info[''node_types'']:
        if cycle_info[''length''] <= 3:
            suspicious = True
            reasons.append(""Device-customer cycle detected - potential account sharing/takeover"")
    
    # Check for referral cycles (Ponzi indicator)
    if ''REFERRED'' in cycle_info[''edge_types'']:
        referral_count = cycle_info[''edge_types''].count(''REFERRED'')
        if referral_count >= 2:
            suspicious = True
            reasons.append(f""Circular referral pattern ({referral_count} referrals) - Ponzi scheme indicator"")
    
    # Check for transaction cycles
    if ''Transaction'' in cycle_info[''node_types''] and cycle_info[''length''] <= 5:
        suspicious = True
        reasons.append(""Transaction involved in cycle - potential structuring or layering"")
    
